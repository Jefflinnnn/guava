// Creates the next workspace (user database) migration from changes to
// prisma/user/schema.prisma.
//
//   pnpm user-db:migration add_expenses
//
// It diffs the schema against prisma/user/migrated.prisma (the schema as of
// the last migration), writes lib/user-db/migrations/NNNN_<name>.ts, updates
// the migrations index and refreshes the snapshot. Review the SQL before
// committing: it runs on every user's database.

import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SCHEMA = "prisma/user/schema.prisma";
const SNAPSHOT = "prisma/user/migrated.prisma";
const DIR = "lib/user-db/migrations";

const name = process.argv[2];
if (!name || !/^[a-z0-9_]+$/.test(name)) {
  console.error("Usage: pnpm user-db:migration <snake_case_name>");
  process.exit(1);
}

const from = existsSync(SNAPSHOT)
  ? ["--from-schema", SNAPSHOT]
  : ["--from-empty"];
const sql = execFileSync(
  "pnpm",
  [
    "exec",
    "prisma",
    "migrate",
    "diff",
    ...from,
    "--to-schema",
    SCHEMA,
    "--script",
  ],
  { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] },
).trim();

if (!sql || sql === "-- This is an empty migration.") {
  console.log("No schema changes since the last migration.");
  process.exit(0);
}

// Code migrations ({ up }) are written by hand in the same folder; they
// count toward the numbering too.
const existing = readdirSync(DIR).filter((f) => /^\d{4}_.+\.ts$/.test(f));
const next = String(existing.length + 1).padStart(4, "0");
const file = `${next}_${name}`;
const escaped = sql
  .replace(/\\/g, "\\\\")
  .replace(/`/g, "\\`")
  .replace(/\$\{/g, "\\${");

writeFileSync(
  join(DIR, `${file}.ts`),
  `// Generated by \`pnpm user-db:migration ${name}\`. Applied to every\n// workspace database; don't edit after it ships.\nconst sql = \`\n${escaped}\n\`;\n\nexport default sql;\n`,
);

const files = [...existing.map((f) => f.slice(0, -3)), file].sort();
const ident = (f) => `m${f.slice(0, 4)}`;
writeFileSync(
  join(DIR, "index.ts"),
  `// Generated by scripts/user-db-migration.mjs. Applied in this order.\nimport type { UserDbMigration } from "./types";\n${files
    .map((f) => `import ${ident(f)} from "./${f}";`)
    .join(
      "\n",
    )}\n\nexport const USER_DB_MIGRATIONS: { name: string; migration: UserDbMigration }[] = [\n${files
    .map((f) => `  { name: "${f}", migration: ${ident(f)} },`)
    .join("\n")}\n];\n`,
);

copyFileSync(SCHEMA, SNAPSHOT);
console.log(`Created ${DIR}/${file}.ts`);
